"""Stub research provider for offline / test use."""

from __future__ import annotations

from youtube_studio.research.providers.base import (
    ResearchProvider,
    ResearchResult,
    RetentionClass,
    utcnow,
)


class StubResearchProvider(ResearchProvider):
    """Returns deterministic fake results – never hits the network."""

    @property
    def name(self) -> str:
        return "stub"

    def search(self, query: str, *, max_results: int = 25) -> list[ResearchResult]:
        now = utcnow()
        results: list[ResearchResult] = []
        for i in range(min(max_results, 5)):
            results.append(
                ResearchResult(
                    provider=self.name,
                    source_type="search_result",
                    external_reference=f"stub:video:{i}",
                    retrieved_at=now,
                    retention_class=RetentionClass.TRANSIENT,
                    payload={
                        "title": f"[Stub] {query} – result {i + 1}",
                        "channel_title": "Stub Channel",
                        "description": f"Synthetic result for query: {query}",
                    },
                    provenance={"note": "Generated by StubResearchProvider – not real data"},
                )
            )
        return results
